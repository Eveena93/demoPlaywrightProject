import{test,expect} from '@playwright/test'
test('End to End testing',async({page})=>{
    await page.goto('https://www.saucedemo.com/')
    const userName=page.locator('#user-name')
    await userName.fill("standard_user")
    const password=page.locator('#password')
    await password.fill("secret_sauce")
    const loginButton=page.locator('#login-button')
    await loginButton.click()
    const selectItem=page.locator('#add-to-cart-sauce-labs-bike-light')
    await selectItem.click()
    const cart=page.locator('#shopping_cart_container')
    await cart.click()
    const checkout=page.locator('#checkout')
    await checkout.click()
    const firstName=page.locator('#first-name')
    await firstName.fill("Eveena")
    const lastName=page.locator('#last-name')
    await lastName.fill("Edison")
    const postalCode=page.locator('#postal-code')
    await postalCode.fill("L4Z 4J1")
    const continueButton=page.locator("#continue")
    await continueButton.click()
    await expect(page.locator(".summary_subtotal_label")).toHaveText("Item total: $9.99")
    const finishButton=page.locator("#finish")
    await finishButton.click()
    await expect(page.locator(".complete-header")).toHaveText("Thank you for your order!")
   
})